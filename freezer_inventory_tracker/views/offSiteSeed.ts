function parseCSVLine(line: string): string[] {
  const parts: string[] = [];
  let inQuotes = false;
  let currentPart = '';
  
  for (let charIdx = 0; charIdx < line.length; charIdx++) {
    const char = line[charIdx];
    if (char === '"') {
      if (inQuotes && line[charIdx + 1] === '"') {
        currentPart += '"';
        charIdx++; // skip escaped quote
      } else {
        inQuotes = !inQuotes;
      }
    } else if (char === ',' && !inQuotes) {
      parts.push(currentPart);
      currentPart = '';
    } else {
      currentPart += char;
    }
  }
  parts.push(currentPart);
  return parts;
}

export function parseCSV(csvText: string): OffSiteEntry[] {
  const lines = csvText.split(/\r?\n/).filter(line => line.trim());
  const result: OffSiteEntry[] = [];
  
  if (lines.length <= 1) return result;
  
  const headerLine = lines[0];
  const headers = parseCSVLine(headerLine).map(h => h.trim().toLowerCase());
  
  // Dynamic header column resolution with fallback aliases
  let serialIdx = headers.findIndex(h => h === 'serial');
  let cutsIdx = headers.findIndex(h => h === 'cuts' || h === 'cut');
  let packDateIdx = headers.findIndex(h => h === 'pack date' || h === 'packdate' || h === 'date');
  let lotIdx = headers.findIndex(h => h === 'lot');
  let piecesIdx = headers.findIndex(h => h === 'pieces' || h === 'piece' || h === '# pieces' || h === 'count' || h === 'qty');
  let netWeightIdx = headers.findIndex(h => h === 'net weight' || h === 'netweight' || h === 'weight' || h === 'lbs');
  let boxIdx = headers.findIndex(h => h === 'box');
  let locationIdx = headers.findIndex(h => h === 'location');
  let palletIdx = headers.findIndex(h => h === 'pallet' || h === 'current');
  let notesIdx = headers.findIndex(h => h === 'notes' || h === 'note');

  // Fallbacks to standard requested index list if not resolved
  if (serialIdx === -1) serialIdx = 0;
  if (cutsIdx === -1) cutsIdx = 1;
  if (packDateIdx === -1) packDateIdx = 2;
  if (lotIdx === -1) lotIdx = 3;
  if (piecesIdx === -1) piecesIdx = 4;
  if (netWeightIdx === -1) netWeightIdx = 5;
  if (boxIdx === -1) boxIdx = 7;
  if (locationIdx === -1) locationIdx = 8;
  if (palletIdx === -1) palletIdx = 9;
  if (notesIdx === -1) notesIdx = 10;

  for (let i = 1; i < lines.length; i++) {
    const parts = parseCSVLine(lines[i]);
    if (parts.length > 0) {
      const serial = parts[serialIdx]?.trim() || '';
      const cuts = parts[cutsIdx]?.trim() || '';
      const packDate = parts[packDateIdx]?.trim() || '';
      const lot = parts[lotIdx]?.trim() || '';
      const pieces = parseInt(parts[piecesIdx]?.trim() || '1', 10) || 1;
      const netWeight = parseFloat(parts[netWeightIdx]?.trim() || '0') || 0;
      const box = parts[boxIdx]?.trim() || '';
      const location = parts[locationIdx]?.trim() || '';
      const pallet = parts[palletIdx]?.trim() || '';
      const notes = parts[notesIdx]?.trim() || '';
      
      result.push({
        id: serial && serial !== '0' ? serial : `auto-${i}-${Math.random().toString(36).substr(2, 5)}`,
        serial,
        cuts,
        packDate,
        lot,
        pieces,
        netWeight,
                box,
        location,
        pallet,
        currentLocation: pallet,
        notes
      });
    }
  }
  return result;
}

